-- =============================================================================
-- SECTION 1: PROFILES TABLE
-- =============================================================================
-- We extend Supabase's built-in auth.users table via a 1-to-1 foreign key.
-- This keeps authentication concerns (passwords, tokens) in auth.users while
-- application-level profile data lives here, in the public schema.

CREATE TABLE IF NOT EXISTS public.profiles (
    -- Primary key mirrors the UUID generated by Supabase Auth on sign-up.
    id              UUID        PRIMARY KEY REFERENCES auth.users (id) ON DELETE CASCADE,

    -- Human-readable display name, populated from sign-up metadata.
    full_name       TEXT        NOT NULL,

    -- Application role. Constrained to exactly two values; no other strings
    -- are accepted at the database level.
    role            TEXT        NOT NULL
                                CHECK (role IN ('student', 'lecturer')),

    -- Only meaningful for students. NULL for lecturers.
    -- Uniqueness is enforced when NOT NULL so two students cannot share
    -- the same matric number.
    matric_number   TEXT        UNIQUE,

    -- Record creation timestamp, set automatically by the database.
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Human-readable comment stored in the database catalogue.
COMMENT ON TABLE public.profiles IS
    'Extended user profile linked 1-to-1 with auth.users. Stores role and '
    'attendance-system-specific fields.';

COMMENT ON COLUMN public.profiles.matric_number IS
    'Student matriculation number. NULL for lecturers. Must be globally unique '
    'when provided.';


-- =============================================================================
-- SECTION 2: AUTOMATIC PROFILE CREATION TRIGGER
-- =============================================================================
-- When a user signs up through Supabase Auth (email/password or any provider),
-- a row is inserted into auth.users. This trigger fires AFTER that insert and
-- immediately creates a corresponding row in public.profiles.
--
-- Callers must pass the following keys inside the `raw_user_meta_data` JSON
-- object during sign-up (e.g. via supabase.auth.signUp({ data: { ... } })):
--
--   full_name     (string, required)
--   role          (string, must be 'student' or 'lecturer')
--   matric_number (string, optional — pass only for students)
--
-- Example client call:
--   await supabase.auth.signUp({
--     email: 'student@uni.edu',
--     password: 'secret',
--     options: {
--       data: {
--         full_name: 'Ada Lovelace',
--         role: 'student',
--         matric_number: 'CSC/2021/042'
--       }
--     }
--   });

CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER                  -- Runs with the privileges of the function
                                  -- owner (postgres), not the signing-up user.
                                  -- Required to write into public.profiles from
                                  -- the auth schema trigger context.
SET search_path = public          -- Prevent search-path hijacking attacks.
AS $$
BEGIN
    INSERT INTO public.profiles (id, full_name, role, matric_number)
    VALUES (
        NEW.id,

        -- Pull full_name from signup metadata; fall back to the email prefix
        -- if the caller forgot to supply it.
        COALESCE(
            NEW.raw_user_meta_data ->> 'full_name',
            split_part(NEW.email, '@', 1)
        ),

        -- role is required. If missing we default to 'student' rather than
        -- failing silently, but you may prefer to raise an exception here.
        COALESCE(NEW.raw_user_meta_data ->> 'role', 'student'),

        -- matric_number is optional; NULL if not provided.
        NEW.raw_user_meta_data ->> 'matric_number'
    );

    RETURN NEW;
END;
$$;

-- Attach the function to auth.users as an AFTER INSERT trigger.
-- The trigger fires once per new user row, never on updates or deletes.
CREATE OR REPLACE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_user();


-- =============================================================================
-- SECTION 3: ROW LEVEL SECURITY (RLS)
-- =============================================================================
-- RLS ensures that even if a bug in application code runs an overly-broad
-- SELECT/UPDATE, the database itself enforces per-row access rules.
--
-- IMPORTANT: Enabling RLS without adding policies blocks ALL access by default.
-- We add explicit PERMISSIVE policies below to re-allow the required operations.

ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;


-- -----------------------------------------------------------------------------
-- Policy 1: "Users can read their own profile"
-- -----------------------------------------------------------------------------
-- Scope:   SELECT only
-- Who:     Any authenticated user
-- What:    Only the row where profiles.id matches the caller's JWT subject (uid)
--
-- This is the baseline policy — every user can always see their own record.
-- Without this, users would not be able to fetch their own profile at all.
CREATE POLICY "Users can view their own profile"
    ON public.profiles
    FOR SELECT
    TO authenticated
    USING (
        auth.uid() = id    -- auth.uid() resolves to the JWT's 'sub' claim
    );


-- -----------------------------------------------------------------------------
-- Policy 2: "Users can update their own profile"
-- -----------------------------------------------------------------------------
-- Scope:   UPDATE only
-- Who:     Any authenticated user
-- What:    Only the row belonging to the caller
--
-- Users can update fields such as full_name. They cannot change their own `role`
-- because the application layer should guard that separately, but if you want
-- the DB to enforce it too, add a WITH CHECK clause:
--   WITH CHECK (role = (SELECT role FROM public.profiles WHERE id = auth.uid()))
CREATE POLICY "Users can update their own profile"
    ON public.profiles
    FOR UPDATE
    TO authenticated
    USING (
        auth.uid() = id    -- Row must belong to the caller to be a candidate
    )
    WITH CHECK (
        auth.uid() = id    -- The resulting row must still belong to the caller
    );


-- -----------------------------------------------------------------------------
-- Policy 3: "Lecturers can read all student profiles"
-- -----------------------------------------------------------------------------
-- Scope:   SELECT only
-- Who:     Authenticated users whose own profile has role = 'lecturer'
-- What:    Any row in profiles where the target user is a student
--
-- This powers the lecturer dashboard where staff need to browse or search
-- students. Note that:
--   a) Lecturers still cannot read OTHER lecturer profiles via this policy
--      (role = 'student' in the USING clause prevents that).
--   b) A lecturer's own profile is accessible via Policy 1 above.
--   c) The sub-SELECT is evaluated once per query against the CALLER's profile.
CREATE POLICY "Lecturers can view all student profiles"
    ON public.profiles
    FOR SELECT
    TO authenticated
    USING (
        -- Is the CALLER a lecturer?
        (
            SELECT role
            FROM public.profiles
            WHERE id = auth.uid()
        ) = 'lecturer'
        AND
        -- Is the TARGET ROW a student?
        role = 'student'
    );


-- =============================================================================
-- SECTION 4: HELPER INDEX
-- =============================================================================
-- Speeds up the sub-SELECT in Policy 3 and any queries that filter by role.
CREATE INDEX IF NOT EXISTS idx_profiles_role
    ON public.profiles (role);

-- Speeds up lookups by matric number (used during attendance verification).
CREATE INDEX IF NOT EXISTS idx_profiles_matric_number
    ON public.profiles (matric_number)
    WHERE matric_number IS NOT NULL;   -- Partial index: skips NULL lecturer rows


